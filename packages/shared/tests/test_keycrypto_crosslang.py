"""
tests/test_keycrypto_crosslang.py
=================================
MANDATORY cross-language acceptance gate for the operator-authorised
(recorded) web private-key import.

Invariant under test
--------------------
trader-core decrypts ``accounts.encrypted_private_key`` ONLY via the FROZEN
``polyecho.shared.crypto.decrypt_private_key``.  The web writes that blob
with ``packages/web/lib/key-crypto.ts`` ``encryptPrivateKey``.  If the TS
blob is not byte-compatible with the Python v1 format, trader-core silently
cannot use the key.  This test PROVES the contract end to end:

    TS  encryptPrivateKey(key, passphrase)  ->  v1 blob
    Py  decrypt_private_key(blob, passphrase) == key      # asserted here

How the two languages meet
--------------------------
The real CI (``.github/workflows/ci.yml`` — mirrored by
``/tmp/everify/v8.sh``) runs the Python job in the ``uv`` image (NO Node)
and the web job in ``node:22`` (NO Python), as two independent legs.  The TS
side (``packages/web/__tests__/lib/key-crypto.test.ts``) therefore writes a
fixture file ``ts_keycrypto_blob.json`` containing a real
TS-produced v1 blob; this Python test reads that fixture and asserts the
FROZEN decryptor recovers the original key.  It is a single file directly
inside THIS already-tracked ``tests/`` dir (deliberately NOT a new subdir:
the CI byte-mirror overlay copies an individual untracked file but
mishandles a brand new untracked directory).  The fixture is regenerated by
the web test on every web-CI run, so it always reflects the CURRENT
``key-crypto.ts``.

Additionally, when Node + the web ``tsx`` runtime are available locally
(developer machine / a combined image), this test ALSO drives the *actual*
``key-crypto.ts`` ``encryptPrivateKey`` through Node and asserts the same
round-trip on a freshly-produced blob — a stronger, no-stale-fixture proof.
That leg is skipped (not failed) when Node/tsx is absent so the canonical
committed-fixture assertion is always the gate.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

from polyecho.shared.crypto import decrypt_private_key

# A single file directly inside THIS already-tracked tests/ dir (NOT a new
# subdir). The CI byte-mirror overlay (/tmp/everify/v8.sh) `git archive
# HEAD`s then overlays `git status --porcelain` entries: it copies an
# individual untracked file (`?? packages/shared/tests/ts_keycrypto_blob
# .json`) but a brand new untracked DIRECTORY is reported as `?? .../dir/`
# and its plain `cp` (no -r) silently fails — so the fixture must live as a
# file in an existing tracked dir, not under a fresh subdir.
_FIXTURE = Path(__file__).parent / "ts_keycrypto_blob.json"
# Repo root: packages/shared/tests/ -> ../../.. == repo root.
_REPO_ROOT = Path(__file__).resolve().parents[3]
_WEB_DIR = _REPO_ROOT / "packages" / "web"
_KEY_CRYPTO_TS = _WEB_DIR / "lib" / "key-crypto.ts"


def test_ts_encrypted_blob_decrypts_with_frozen_python() -> None:
    """CANONICAL GATE: the FROZEN Python ``decrypt_private_key`` recovers
    the original key from the committed TS-produced v1 blob.

    This is byte-level proof that ``key-crypto.ts`` produced a blob the
    frozen trader-core decryptor accepts (same header/AAD, big-endian
    iteration packing, PBKDF2-HMAC-SHA256 over UTF-8 passphrase bytes,
    AES-256-GCM)."""
    assert _FIXTURE.is_file(), (
        f"missing cross-language fixture {_FIXTURE} — the web vitest "
        "(packages/web/__tests__/lib/key-crypto.test.ts) regenerates it on "
        "every web-CI run; run the web test suite to (re)produce it."
    )
    data = json.loads(_FIXTURE.read_text(encoding="utf-8"))

    blob = bytes.fromhex(data["blob_hex"])
    passphrase = data["passphrase"]
    expected_key = data["private_key"]

    # v1 sanity: first byte is the version tag, header carries the iter.
    assert blob[0] == 0x01, "fixture blob is not a v1 blob (version byte)"
    assert len(blob) >= 65, "fixture blob shorter than the v1 minimum (65B)"

    recovered = decrypt_private_key(blob, passphrase)
    assert recovered == expected_key

    # Wrong passphrase must NOT silently return garbage (GCM-authenticated).
    from cryptography.exceptions import InvalidTag

    with pytest.raises(InvalidTag):
        decrypt_private_key(blob, passphrase + "x")


def _node_and_tsx_available() -> bool:
    if shutil.which("node") is None:
        return False
    # The web package's local tsx runner (used to execute the TS module).
    return (_WEB_DIR / "node_modules" / ".bin" / "tsx").exists()


@pytest.mark.skipif(
    not _node_and_tsx_available(),
    reason=(
        "Node + web tsx runtime not available (e.g. the python-only CI "
        "leg) — the committed-fixture assertion above is the canonical "
        "cross-language gate; this is the stronger no-stale-fixture leg."
    ),
)
def test_live_ts_keycrypto_roundtrips_through_python() -> None:
    """STRONGER (when Node is present): drive the ACTUAL key-crypto.ts
    ``encryptPrivateKey`` via Node+tsx, then decrypt with the FROZEN Python
    decryptor.  Proves the live TS module (not just a committed snapshot)
    is byte-compatible."""
    pk = "0x" + "cd" * 32
    passphrase = "live-cross-lang 台灣-測試 ñ"
    # ESM driver: import the real module, print the v1 blob as hex on stdout.
    driver = (
        "import { encryptPrivateKey } from "
        f"{json.dumps(str(_KEY_CRYPTO_TS))};\n"
        "const pk = process.env.PE_PK;\n"
        "const pp = process.env.PE_PP;\n"
        "const blob = await encryptPrivateKey(pk, pp);\n"
        "process.stdout.write(blob.toString('hex'));\n"
    )
    env = dict(os.environ)
    env["PE_PK"] = pk
    env["PE_PP"] = passphrase
    # Pin the KDF iterations low so PBKDF2 is fast on both sides; the TS
    # clamp floors this at 100000 (== the Python MIN_KDF_ITERATIONS).
    env["POLYECHO_KEY_KDF_ITERATIONS"] = "100000"

    proc = subprocess.run(  # noqa: S603 - fixed local tsx runner, no shell
        [
            str(_WEB_DIR / "node_modules" / ".bin" / "tsx"),
            "--eval",
            driver,
        ],
        cwd=str(_WEB_DIR),
        env=env,
        capture_output=True,
        text=True,
        timeout=120,
    )
    assert proc.returncode == 0, (
        f"tsx driver failed (rc={proc.returncode}). stderr:\n{proc.stderr}"
    )
    blob_hex = proc.stdout.strip()
    assert blob_hex, f"tsx driver produced no blob. stderr:\n{proc.stderr}"
    blob = bytes.fromhex(blob_hex)

    assert blob[0] == 0x01
    assert int.from_bytes(blob[1:5], "big") == 100_000  # clamped, BE uint32
    assert decrypt_private_key(blob, passphrase) == pk
