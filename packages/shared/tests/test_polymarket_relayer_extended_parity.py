"""
TS-reference byte parity tests for relayer_extended.py (P6).

Fixtures generated by running ``Polymarket/builder-relayer-client`` TS source
directly (viem ABI encoder, eth_sign / signTypedData). See fixture ``_meta``
field for source repo + SHA + date.

These tests verify byte-identical wire format against the upstream TS:

  - sig 1 (PROXY / Magic):
      * magic_proxy_address(eoa) CREATE2 result
      * inner CTF.redeemPositions(...) calldata
      * outer ProxyFactory.proxy([call]) calldata
      * "rlx:" struct hash
      * eth_sign signature (deterministic ECDSA k via canonical RFC-6979)
      * /submit body shape (including `to` = ProxyFactory)

  - sig 3 (DEPOSIT_WALLET / 1271):
      * deposit_wallet_address(eoa) CREATE2 result (Solady ERC-1967, n byte)
      * inner CTF.redeemPositions(...) calldata
      * EIP-712 Batch signature with DepositWallet domain
      * /submit body shape (including `to` = DepositWalletFactory)

The Hardhat account-#0 private key used in fixtures
(``0xac0974…f2ff80``) is a WELL-KNOWN PUBLIC TEST KEY shipped in every
Hardhat install (https://hardhat.org). It is NOT a production key and
holds no funds on mainnet.

If a test fails, the fixture is the source of truth — bug fix goes in
``relayer_extended.py`` / ``wallet.py``, never in the fixture.
"""

