def test_proxy_struct_hash_matches_ts() -> None:
    """Brief UNVERIFIED #1 (`to` semantics) + #3 (gasLimit handling).

    The TS reference passes `to = ProxyFactory` (NOT relay address) to the
    struct hash and to /submit.  This test pins both behaviours.
    """
    v = FIXTURES["proxy_redeem"]
    inp = v["input"]
    outer_data_bytes = bytes.fromhex(v["outer_calldata"][2:])
    struct_hash = RX._proxy_struct_hash(
        eoa=inp["eoa"],
        proxy_factory=FIXTURES["addresses"]["proxy_factory"],
        data=outer_data_bytes,
        tx_fee=int(inp["tx_fee"]),
        gas_price=int(inp["gas_price"]),
        gas_limit=int(inp["gas_limit"]),
        nonce=int(inp["nonce"]),
        relay_hub=FIXTURES["addresses"]["relay_hub"],
        relay=inp["relay"],
    )
    assert "0x" + struct_hash.hex() == v["struct_hash"], (
        f"struct hash drift: py=0x{struct_hash.hex()} ts={v['struct_hash']}"
    )


def test_proxy_signature_matches_ts() -> None:
    """Brief UNVERIFIED #2 (eth_sign details).

    The TS reference uses ``signer.signMessage(structHash)`` which on a
    viem account signs the EIP-191 ``\\x19Ethereum Signed Message:\\n32``
    prefixed digest — NOT a raw 32-byte ECDSA over structHash.  This test
    forces us to use the EIP-191 path; if Python is doing raw ``_sign_hash``
    it will fail loudly here.
    """
    v = FIXTURES["proxy_redeem"]
    inp = v["input"]
    struct_hash = bytes.fromhex(v["struct_hash"][2:])
    sig = RX._sign_proxy(struct_hash, inp["private_key"])
    assert sig.lower() == v["signature"].lower(), (
        f"eth_sign signature drift:\n  py={sig}\n  ts={v['signature']}"
    )


