def test_deposit_wallet_typed_data_signature_matches_ts() -> None:
    """EIP-712 Batch signature with DepositWallet domain."""
    v = FIXTURES["deposit_wallet_redeem"]
    inp = v["input"]
    inner_bytes = bytes.fromhex(v["inner_calldata"][2:])
    wallet_addr = FIXTURES["deposit_wallet"]["expected_wallet"]
    sig = RX._sign_wallet_batch(
        wallet_address=wallet_addr,
        chain_id=inp["chain_id"],
        nonce=int(inp["nonce"]),
        deadline=int(inp["deadline"]),
        calls=[
            {
                "target": inp["target"],
                "value": 0,
                "data": inner_bytes,
            }
        ],
        private_key=inp["private_key"],
    )
    assert sig.lower() == v["signature"].lower(), (
        f"EIP-712 signature drift:\n  py={sig}\n  ts={v['signature']}"
    )


