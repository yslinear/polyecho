def test_proxy_submit_body_to_field_is_proxy_factory() -> None:
    """The /submit `to` field MUST be ProxyFactory (not relay, not proxyWallet).

    Brief UNVERIFIED #1 fixed-point.
    """
    v = FIXTURES["proxy_redeem"]
    expected_factory = FIXTURES["addresses"]["proxy_factory"].lower()
    expected_proxy = FIXTURES["magic_proxy"]["expected_proxy"].lower()
    assert v["expected_body"]["to"].lower() == expected_factory
    assert v["expected_body"]["from"].lower() == v["input"]["eoa"].lower()
    assert v["expected_body"]["proxyWallet"].lower() == expected_proxy


def test_deposit_wallet_submit_body_to_field_is_factory() -> None:
    """The /submit `to` field for WALLET MUST be DepositWalletFactory."""
    v = FIXTURES["deposit_wallet_redeem"]
    expected_factory = FIXTURES["addresses"]["deposit_wallet_factory"].lower()
    assert v["expected_body"]["to"].lower() == expected_factory
    assert (
        v["expected_body"]["depositWalletParams"]["depositWallet"].lower()
        == FIXTURES["deposit_wallet"]["expected_wallet"].lower()
    )
