def test_redeem_positions_inner_calldata_matches_ts() -> None:
    """CTF.redeemPositions selector + ABI-encoded body."""
    v = FIXTURES["proxy_redeem"]
    inp = v["input"]
    got = RX._encode_redeem_positions(
        collateral=inp["collateral"],
        condition_id=inp["condition_id"],
        index_sets=inp["index_sets"],
    )
    assert "0x" + got.hex() == v["inner_calldata"], (
        f"inner calldata drift:\n  py={('0x' + got.hex())}\n  ts={v['inner_calldata']}"
    )


def test_proxy_outer_calldata_matches_ts() -> None:
    """ProxyFactory.proxy([(typeCode,to,value,data)]) wrapper calldata.

    This is the brief's UNVERIFIED #5 — the ABI tuple ordering.  The TS
    `proxyWalletFactory` ABI defines components in order
    ``[typeCode uint8, to address, value uint256, data bytes]``, so the
    selector is ``proxy((uint8,address,uint256,bytes)[])`` = ``0x34ee9791``.
    """
    v = FIXTURES["proxy_redeem"]
    inp = v["input"]
    inner = RX._encode_redeem_positions(
        collateral=inp["collateral"],
        condition_id=inp["condition_id"],
        index_sets=inp["index_sets"],
    )
    outer = RX._encode_proxy_batch([(1, RX.CTF_ADDRESS, 0, inner)])
    assert "0x" + outer.hex() == v["outer_calldata"], (
        f"outer proxy([call]) calldata drift:\n"
        f"  py_selector={('0x' + outer.hex())[:10]}\n"
        f"  ts_selector={v['outer_calldata'][:10]}\n"
        f"  py_body={('0x' + outer.hex())}\n"
        f"  ts_body={v['outer_calldata']}"
    )


